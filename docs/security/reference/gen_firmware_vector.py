#!/usr/bin/env python3
"""Writes firmware/CircuitBleDisplay/main/circuit_selftest_vector.h from the shared
test vectors, so the board checks its own crypto at every start."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[3]
v = json.loads((root / "docs/security/test-vectors.json").read_text())


def arr(name, hexstr):
    data = bytes.fromhex(hexstr)
    body = ",\n    ".join(", ".join(f"0x{b:02X}" for b in data[i : i + 16]) for i in range(0, len(data), 16))
    return f"static const uint8_t {name}[] = {{\n    {body}\n}};\n"


out = ["#pragma once\n\n// Generated by docs/security/reference/gen_firmware_vector.py. Do not edit.\n\n#include <cstdint>\n\n"]
out.append(f"static const uint32_t kVectorKeyId = 0x{v['keyId']:08X};\n")
out.append(f"static const uint32_t kVectorNoteId = {v['noteId']};\n")
out.append(f"static const uint32_t kVectorChunk = {v['chunkSize']};\n")
out.append(arr("kVectorMasterKey", v["masterKeyHex"]))
for i, c in enumerate(v["cases"]):
    out.append(arr(f"kVectorPcm{i}", c["plaintextHex"]))
    out.append(f"static const unsigned kVectorPcm{i}Len = {len(c['plaintextHex']) // 2};\n")
    out.append(arr(f"kVectorFile{i}", c["fileHex"]))
    out.append(f"static const unsigned kVectorFile{i}Len = {len(c['fileHex']) // 2};\n")
out.append(f"static const unsigned kVectorCases = {len(v['cases'])};\n")
target = root / "firmware/CircuitBleDisplay/main/circuit_selftest_vector.h"
target.write_text("".join(out))
print("wrote", target.relative_to(root), f"({len(v['cases'])} cases)")
