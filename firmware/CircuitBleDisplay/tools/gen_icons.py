#!/usr/bin/env python3
"""Rasterise Lucide icons (tools/lucide/*.svg) into 1-bit rows for relayout_screens.py.

Needs `svgelements` and Pillow (a throwaway venv is fine). Writes icon_bitmaps.py.
"""
from pathlib import Path

from PIL import Image, ImageDraw
from svgelements import SVG, Close, Move, Path as SvgPath

HERE = Path(__file__).resolve().parent
# name -> (pixel size, stroke width in the 24-unit grid)
ICONS = {"wifi": (20, 1.9), "wifi-off": (20, 1.9), "wifi-low": (20, 1.9), "wifi-high": (20, 1.9),
         "wifi-zero": (20, 1.9), "phone": (18, 2.3), "hard-drive": (18, 2.3),
         "clock": (14, 2.4), "check": (14, 2.8), "bluetooth": (18, 2.0), "mic-off": (28, 2.2)}


def polylines(svg_file):
    polys = []
    for shape in SVG.parse(str(svg_file)).elements():
        if not hasattr(shape, "segments"):
            continue
        for seg in SvgPath(shape):
            if isinstance(seg, Move):
                polys.append([seg.end])
            elif isinstance(seg, Close):
                polys[-1].append(polys[-1][0])
            else:
                polys[-1] += [seg.point(i / 40) for i in range(1, 41)]
    return polys


def raster(name, size, stroke):
    ss = 16
    unit = size * ss / 24
    im = Image.new("L", (size * ss, size * ss), 255)
    dr = ImageDraw.Draw(im)
    w = max(1, round(stroke * unit))
    for poly in polylines(HERE / "lucide" / f"{name}.svg"):
        pts = [(float(p.x) * unit, float(p.y) * unit) for p in poly]
        if len(pts) < 2:  # single dot ("h.01" paths collapse to a tiny segment)
            pts = pts * 2
        dr.line(pts, fill=0, width=w, joint="curve")
        for x, y in (pts[0], pts[-1]):
            dr.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=0)
    im = im.resize((size, size), Image.LANCZOS)
    return ["".join("#" if im.getpixel((x, y)) < 140 else "." for x in range(size)) for y in range(size)]


out = ['"""Generated by gen_icons.py from Lucide icons. Do not edit."""\n', "ICONS = {\n"]
for name, (size, stroke) in ICONS.items():
    rows = raster(name, size, stroke)
    out.append(f'    "{name}": [\n' + "".join(f'        "{r}",\n' for r in rows) + "    ],\n")
out.append("}\n")
(HERE / "icon_bitmaps.py").write_text("".join(out))
