#!/usr/bin/env python3
"""Draws the Moment (bookmark) icon into main/circuit_moment_icon.h. No packages needed.

The shape is the Lucide "bookmark" icon (ISC licence), path
  m19 21-7-4-7 4V5a2 2 0 0 1 2-2h10a2 2 0 0 1 2 2v16z   on a 24 x 24 grid, stroke 2.
Two 1-bit images, in the format the other icons use: an outline and a filled bookmark. The recording
screen alternates them on each tap, so every tap changes the picture.
"""
import math
from pathlib import Path

SIZE = 20
STROKE = 2.0  # in the 24-unit grid, as Lucide draws it
SS = 6        # samples per pixel side


def outline():
    pts = [(19, 21), (12, 17), (5, 21), (5, 5)]
    pts += [(7 + 2 * math.cos(math.radians(a)), 5 + 2 * math.sin(math.radians(a))) for a in range(180, 271, 10)]
    pts += [(17 + 2 * math.cos(math.radians(a)), 5 + 2 * math.sin(math.radians(a))) for a in range(270, 361, 10)]
    pts += [(19, 21)]
    return pts


def dist_to_segment(px, py, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    t = 0 if dx == dy == 0 else max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def inside(px, py, poly):
    hit = False
    for (ax, ay), (bx, by) in zip(poly, poly[1:] + poly[:1]):
        if (ay > py) != (by > py) and px < (bx - ax) * (py - ay) / (by - ay) + ax:
            hit = not hit
    return hit


def render(filled):
    poly = outline()
    unit = 24 / SIZE
    rows = []
    for y in range(SIZE):
        row = ""
        for x in range(SIZE):
            ink = 0
            for sy in range(SS):
                for sx in range(SS):
                    px = (x + (sx + .5) / SS) * unit
                    py = (y + (sy + .5) / SS) * unit
                    near = min(dist_to_segment(px, py, a, b) for a, b in zip(poly, poly[1:])) <= STROKE / 2
                    if near or (filled and inside(px, py, poly)):
                        ink += 1
            row += "#" if ink * 2 >= SS * SS else "."
        rows.append(row)
    return rows


def c_image(name, rows):
    stride = (SIZE + 7) // 8
    data = [0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF]  # palette: black, white (opaque)
    for row in rows:
        bits = [0 if c == "#" else 1 for c in row] + [1] * (stride * 8 - SIZE)
        for i in range(stride):
            data.append(sum(b << (7 - j) for j, b in enumerate(bits[i * 8:i * 8 + 8])))
    body = ",\n    ".join(", ".join("0x%02X" % v for v in data[i:i + 12]) for i in range(0, len(data), 12))
    return f"""static const uint8_t {name}_data[] = {{
    {body},
}};
static const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_I1,
        .flags = 0,
        .w = {SIZE},
        .h = {SIZE},
        .stride = {stride},
        .reserved_2 = 0,
    }},
    .data_size = sizeof({name}_data),
    .data = {name}_data,
    .reserved = nullptr,
    .reserved_2 = nullptr,
}};
"""


if __name__ == "__main__":
    outline_rows, filled_rows = render(False), render(True)
    for title, rows in (("outline", outline_rows), ("filled", filled_rows)):
        print(title)
        print("\n".join(rows))
    header = ('#pragma once\n#include "lvgl.h"\n\n// Generated by tools/gen_moment_icon.py (Lucide "bookmark"). Do not edit.\n'
              + c_image("circuit_moment_outline", outline_rows) + "\n" + c_image("circuit_moment_filled", filled_rows))
    (Path(__file__).resolve().parents[1] / "main" / "circuit_moment_icon.h").write_text(header)
    print("wrote main/circuit_moment_icon.h")
